import {
  BadRequestException,
  Injectable,
  Logger,
  ServiceUnavailableException,
} from '@nestjs/common';
import { ConfigService } from '@nestjs/config';
import { createWriteStream, promises as fs } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';
import { Readable } from 'stream';
import { pipeline } from 'stream/promises';
import type { ReadableStream as WebReadableStream } from 'stream/web';
import { v4 as uuid } from 'uuid';
import { AuctionCategory } from '../prize/enums/auction-category.enum';
import {
  AuctionsMediaService,
  VIDEO_MAX_BYTES,
} from './auctions-media.service';
import type { AuctionVideo } from './hermes.types';

/**
 * 360° spin videos for Hermes lots, generated by Pika's keyframe model
 * (https://dev.pika.art, `pika/pikaframes/image-to-video`).
 *
 * The admin picks a front and a back photo; we send `[front, back]` with
 * `loop: true`, so Pika animates front → back → front and the clip loops
 * seamlessly. The finished MP4 is copied into our media bucket (Pika's
 * file URLs aren't ours to keep) and returned as an `upload` video flagged
 * `spin: true`. Nothing is attached to an auction here: the admin previews
 * it and decides whether to include it, and the normal save stores it.
 *
 * Stateless by design: the Pika job id is the handle, so any API task can
 * answer a status poll. Dormant until `PIKA_API_KEY` is set.
 */
const PIKA_BASE = 'https://api.dev.pika.art';
const PIKA_SUBMIT_PATH = '/v1/media/pika/pikaframes/image-to-video';
const JOB_ID_RE = /^media_[0-9a-f-]{36}$/i;

const SPIN_RESOLUTION = '1080p';
/** Seconds per half turn (front → back, then back → front). */
const SPIN_HALF_TURN_SECONDS = 3;
/** Pika 2.5 Keyframe list price at 1080p, per output second. */
const PIKA_USD_PER_SECOND = 0.06;
const SPIN_SECONDS = SPIN_HALF_TURN_SECONDS * 2;

const PIKA_ERROR_HINT: Record<string, string> = {
  insufficient_balance:
    'The Pika account is out of credit. Top it up at dev.pika.art/billing and try again.',
  cycle_limit_exceeded:
    "The Pika account hit this billing cycle's spend limit.",
  content_moderation:
    "Pika's safety filter refused these photos. Try a different front/back pair.",
  invalid_input:
    "Pika couldn't use these photos. Make sure both are clear JPG/PNG/WebP shots.",
  rate_limited: 'Pika is rate-limiting us right now. Try again in a minute.',
  provider_unavailable: 'Pika is temporarily unavailable. Try again shortly.',
  provider_timeout: 'Pika timed out generating the spin. Try again.',
  timed_out: 'Pika timed out generating the spin. Try again.',
  membership_required: 'The Pika account needs an active membership.',
  admission_suspended: 'The Pika account is suspended.',
};

interface PikaJob {
  id?: string;
  status?: 'queued' | 'running' | 'completed' | 'failed' | 'cancelled';
  output?: { video?: { url?: string; content_type?: string } } | null;
  error?: { code?: string; message?: string } | null;
  billing?: { state?: string; charge_micro_usd?: number } | null;
  message?: string;
}

export interface SpinConfig {
  enabled: boolean;
  seconds: number;
  resolution: string;
  estimatedCostUsd: number;
}

export interface SpinStatus {
  jobId: string;
  status: 'queued' | 'running' | 'completed' | 'failed';
  /** Present once completed and copied to our bucket. */
  video?: AuctionVideo;
  error?: string;
}

@Injectable()
export class AuctionsSpinService {
  private readonly logger = new Logger(AuctionsSpinService.name);
  /** Job id → our stored video, so repeat polls don't re-copy the MP4. */
  private readonly stored = new Map<string, AuctionVideo>();
  private readonly copying = new Map<string, Promise<AuctionVideo>>();

  constructor(
    private readonly config: ConfigService,
    private readonly media: AuctionsMediaService,
  ) {}

  private apiKey(): string | null {
    return (
      this.config.get<string>('PIKA_API_KEY') ||
      process.env.PIKA_API_KEY ||
      null
    );
  }

  getConfig(): SpinConfig {
    return {
      enabled: !!this.apiKey(),
      seconds: SPIN_SECONDS,
      resolution: SPIN_RESOLUTION,
      estimatedCostUsd:
        Math.round(SPIN_SECONDS * PIKA_USD_PER_SECOND * 100) / 100,
    };
  }

  private requireKey(): string {
    const key = this.apiKey();
    if (!key) {
      throw new ServiceUnavailableException(
        '360° spins are not configured (missing PIKA_API_KEY).',
      );
    }
    return key;
  }

  /** Only our own bucket's photos go to Pika (no arbitrary URLs). */
  private isOurPhoto(url: string): boolean {
    try {
      const u = new URL(url);
      const bucket = this.config.get<string>('AWS_DEFAULT_S3_BUCKET') || '';
      return (
        u.protocol === 'https:' &&
        u.hostname.endsWith('.amazonaws.com') &&
        u.pathname.includes('/hermes/images/') &&
        (!bucket ||
          u.hostname.startsWith(`${bucket}.`) ||
          u.pathname.startsWith(`/${bucket}/`))
      );
    } catch {
      return false;
    }
  }

  private prompts(category?: AuctionCategory) {
    const noun =
      category === AuctionCategory.SPORTS_MEMORABILIA
        ? 'collectible'
        : 'trading card';
    const turn = (from: string, to: string) =>
      `The ${noun} turns smoothly on its vertical axis from its ${from} to its ${to}, like a product on a turntable. Constant rotation speed, locked-off camera, plain dark studio background, sharp focus. The ${noun} stays rigid and keeps its exact printed design.`;
    return {
      transition_prompts: [turn('front', 'back'), turn('back', 'front')],
      negative_prompt:
        'bending, warping, melting, morphing, changing artwork or text, extra objects, hands, camera movement, zoom, cuts, blur, low quality',
    };
  }

  private async pika(
    path: string,
    init: RequestInit & { idempotencyKey?: string } = {},
  ): Promise<{ status: number; body: PikaJob }> {
    const key = this.requireKey();
    const res = await fetch(`${PIKA_BASE}${path}`, {
      ...init,
      headers: {
        'X-API-Key': key,
        'Content-Type': 'application/json',
        ...(init.idempotencyKey
          ? { 'Idempotency-Key': init.idempotencyKey }
          : {}),
      },
      signal: AbortSignal.timeout(30_000),
    });
    const body = (await res.json().catch(() => ({}))) as PikaJob;
    return { status: res.status, body };
  }

  private failure(job: PikaJob, httpStatus?: number): string {
    const code = job.error?.code;
    if (code && PIKA_ERROR_HINT[code]) return PIKA_ERROR_HINT[code];
    if (httpStatus === 401)
      return 'Pika rejected our API key (PIKA_API_KEY). Replace it and redeploy.';
    return (
      job.error?.message ||
      job.message ||
      'Pika could not generate the spin. Try again.'
    );
  }

  /** Submits a front → back → front spin. Returns the Pika job id to poll. */
  async start(params: {
    frontUrl: string;
    backUrl: string;
    category?: AuctionCategory;
    adminId: string;
  }): Promise<SpinStatus> {
    this.requireKey();
    if (params.frontUrl === params.backUrl) {
      throw new BadRequestException('Pick two different photos.');
    }
    if (!this.isOurPhoto(params.frontUrl) || !this.isOurPhoto(params.backUrl)) {
      throw new BadRequestException(
        'Spins can only be made from photos uploaded to this auction.',
      );
    }

    const body = {
      resolution: SPIN_RESOLUTION,
      images: [params.frontUrl, params.backUrl],
      loop: true,
      transition_durations_s: [SPIN_HALF_TURN_SECONDS, SPIN_HALF_TURN_SECONDS],
      ...this.prompts(params.category),
    };
    let res: { status: number; body: PikaJob };
    try {
      res = await this.pika(PIKA_SUBMIT_PATH, {
        method: 'POST',
        body: JSON.stringify(body),
        idempotencyKey: uuid(),
      });
    } catch (err) {
      this.logger.error(`Pika submit failed: ${(err as Error).message}`);
      throw new ServiceUnavailableException(
        "Couldn't reach Pika. Try again shortly.",
      );
    }

    const job = res.body;
    if (!job.id || job.status === 'failed' || job.status === 'cancelled') {
      this.logger.warn(
        `Pika spin rejected (${res.status}) ${job.error?.code ?? ''}: ${job.error?.message ?? job.message ?? ''}`,
      );
      throw new BadRequestException(this.failure(job, res.status));
    }
    this.logger.log(
      `Pika spin ${job.id} submitted by admin ${params.adminId} (~$${this.getConfig().estimatedCostUsd})`,
    );
    return {
      jobId: job.id,
      status: job.status === 'running' ? 'running' : 'queued',
    };
  }

  /** Polls Pika; on completion copies the MP4 into our bucket once. */
  async status(jobId: string): Promise<SpinStatus> {
    if (!JOB_ID_RE.test(jobId)) {
      throw new BadRequestException('Unknown spin job.');
    }
    const cached = this.stored.get(jobId);
    if (cached) return { jobId, status: 'completed', video: cached };

    let res: { status: number; body: PikaJob };
    try {
      res = await this.pika(`/v1/media/jobs/${jobId}`);
    } catch (err) {
      this.logger.warn(`Pika poll ${jobId} failed: ${(err as Error).message}`);
      // Transient — the client keeps polling.
      return { jobId, status: 'running' };
    }
    if (res.status === 404) {
      throw new BadRequestException('Unknown spin job.');
    }
    const job = res.body;
    if (job.status === 'failed' || job.status === 'cancelled') {
      return { jobId, status: 'failed', error: this.failure(job, res.status) };
    }
    if (job.status !== 'completed') {
      return { jobId, status: job.status === 'running' ? 'running' : 'queued' };
    }

    const sourceUrl = job.output?.video?.url;
    if (!sourceUrl) {
      return {
        jobId,
        status: 'failed',
        error: 'Pika finished but returned no video. Try again.',
      };
    }
    try {
      const charge =
        job.billing?.state === 'settled'
          ? (job.billing.charge_micro_usd ?? 0) / 1e6
          : null;
      const video = await this.copyOnce(jobId, sourceUrl, charge);
      return { jobId, status: 'completed', video };
    } catch (err) {
      this.logger.error(
        `Copying Pika spin ${jobId} to S3 failed: ${(err as Error).message}`,
      );
      return {
        jobId,
        status: 'failed',
        error:
          err instanceof BadRequestException
            ? err.message
            : "The spin was generated but couldn't be saved to storage. Try again.",
      };
    }
  }

  private copyOnce(
    jobId: string,
    sourceUrl: string,
    chargeUsd: number | null,
  ): Promise<AuctionVideo> {
    let p = this.copying.get(jobId);
    if (p === undefined) {
      p = this.copy(jobId, sourceUrl)
        .then((video) => {
          this.stored.set(jobId, video);
          this.logger.log(
            `Pika spin ${jobId} saved to ${video.key}` +
              (chargeUsd !== null ? ` (charged $${chargeUsd.toFixed(2)})` : ''),
          );
          return video;
        })
        .finally(() => this.copying.delete(jobId));
      this.copying.set(jobId, p);
    }
    return p;
  }

  private async copy(jobId: string, sourceUrl: string): Promise<AuctionVideo> {
    const src = new URL(sourceUrl);
    if (src.protocol !== 'https:') {
      throw new Error(`refusing non-https Pika output ${src.origin}`);
    }
    // Only Pika's own API host gets our key.
    const headers: Record<string, string> =
      src.origin === PIKA_BASE ? { 'X-API-Key': this.requireKey() } : {};
    const res = await fetch(src, {
      headers,
      signal: AbortSignal.timeout(120_000),
    });
    if (!res.ok || !res.body) {
      throw new Error(`download ${res.status}`);
    }
    const length = Number(res.headers.get('content-length') ?? 0);
    if (length > VIDEO_MAX_BYTES)
      throw new Error(`video too large (${length})`);

    const tmp = join(tmpdir(), `hermes-spin-${uuid()}.mp4`);
    try {
      await pipeline(
        Readable.fromWeb(res.body as unknown as WebReadableStream),
        createWriteStream(tmp),
      );
      const key = `hermes/spins/${jobId}.mp4`;
      const url = await this.media.storeGenerated(key, tmp, 'video/mp4');
      return { kind: 'upload', url, key, spin: true };
    } finally {
      await fs.unlink(tmp).catch(() => undefined);
    }
  }
}
